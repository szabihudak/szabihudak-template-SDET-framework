import * as babel from "prettier/plugins/babel";
import * as estree from "prettier/plugins/estree";
import * as markdown from "prettier/plugins/markdown";
import * as typescript from "prettier/plugins/typescript";

import {
  AGENTS,
  answerErrors,
  BUILD_PIPELINE,
  generateProject,
  type Answers,
  type ProjectFiles,
} from "../project-generator";

// The configurator page's generator: the same project generation as setup.ts,
// with prettier's browser build and the template files from template.json
// (framework/tools/configurator/build.ts). Exposed as globalThis.SdetGenerator.

export type TemplateBundle = {
  templateVersion: string;
  files: Record<string, string>;
  projectFiles: string[];
  executable: string[];
  exclusions: ProjectFiles;
  // package-lock.json without the performance devDependencies, generated by
  // npm when the bundle is built; setup.ts generates the same with npm.
  lockWithoutPerformance: string;
};

const plugins = [babel, estree, markdown, typescript];

const format = (content: string, file: string) =>
  prettier.format(content, { filepath: file, plugins });

async function generate(answers: Answers, bundle: TemplateBundle) {
  const errors = answerErrors(answers);
  if (errors.length > 0) {
    throw new Error(`Invalid setup answers:\n${errors.join("\n")}`);
  }

  return generateProject(
    answers,
    {
      files: bundle.files,
      projectFiles: bundle.projectFiles,
      executable: bundle.executable,
      exclusions: bundle.exclusions,
      packageLock: async () => bundle.lockWithoutPerformance,
    },
    format,
  );
}

// A zip of stored (uncompressed) entries under one folder, with Unix modes so
// install.sh stays executable after unzip.
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function zip(
  folder: string,
  files: Record<string, string>,
  executable: string[],
): Uint8Array {
  const encoder = new TextEncoder();
  const local: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;

  for (const file of Object.keys(files).sort()) {
    const name = encoder.encode(`${folder}/${file}`);
    const data = encoder.encode(files[file]);
    const crc = crc32(data);
    const mode = executable.includes(file) ? 0o100755 : 0o100644;

    const header = new DataView(new ArrayBuffer(30));
    header.setUint32(0, 0x04034b50, true);
    header.setUint16(4, 20, true);
    header.setUint16(6, 0x0800, true); // UTF-8 names
    header.setUint32(14, crc, true);
    header.setUint32(18, data.length, true);
    header.setUint32(22, data.length, true);
    header.setUint16(26, name.length, true);
    local.push(new Uint8Array(header.buffer), name, data);

    const entry = new DataView(new ArrayBuffer(46));
    entry.setUint32(0, 0x02014b50, true);
    entry.setUint16(4, (3 << 8) | 20, true); // made by Unix
    entry.setUint16(6, 20, true);
    entry.setUint16(8, 0x0800, true);
    entry.setUint32(16, crc, true);
    entry.setUint32(20, data.length, true);
    entry.setUint32(24, data.length, true);
    entry.setUint16(28, name.length, true);
    entry.setUint32(38, (mode << 16) >>> 0, true);
    entry.setUint32(42, offset, true);
    central.push(new Uint8Array(entry.buffer), name);

    offset += 30 + name.length + data.length;
  }

  const centralSize = central.reduce((size, part) => size + part.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true);
  end.setUint16(8, central.length / 2, true);
  end.setUint16(10, central.length / 2, true);
  end.setUint32(12, centralSize, true);
  end.setUint32(16, offset, true);

  const parts = [...local, ...central, new Uint8Array(end.buffer)];
  const result = new Uint8Array(
    parts.reduce((size, part) => size + part.length, 0),
  );
  let position = 0;
  for (const part of parts) {
    result.set(part, position);
    position += part.length;
  }
  return result;
}

(globalThis as Record<string, unknown>).SdetGenerator = {
  AGENTS,
  BUILD_PIPELINE,
  validate: answerErrors,
  generate,
  zip,
};
