import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { AST_NODE_TYPES as T } from "@typescript-eslint/utils";
import type { TSESTree } from "@typescript-eslint/utils";
import tseslint from "typescript-eslint";

// The architecture checks ESLint cannot run on one source file: test plans
// against their specs, automation files, and the written source behind every
// rule. Source code rules are in framework/tools/eslint.config.mjs and
// framework/tools/eslint-plugin/; `npm run lint:architecture` runs both.

const ROOT = path.resolve(__dirname, "../..");

// Every rule cites the written rule it enforces as "<file>#<heading anchor>".
// The check fails when a cited section does not exist, so no rule can exist
// without a documented rule behind it.
const RULE_FILES =
  /^framework\/tools\/(eslint\.config\.mjs|eslint-plugin\/rules\/[^/]+\.ts)$/;
const CITATION = /(?:AGENTS\.md|framework\/docs\/[\w./-]+\.md)#[\w-]+/g;

const CASE_ID_TITLE_CHECK = {
  id: "planned-case-id-in-test-title",
  source: "AGENTS.md#playwright-rules",
};

// Baselines are approved by a human, never regenerated by automation.
const SNAPSHOT_UPDATE_CHECK = {
  id: "no-snapshot-update-in-automation",
  source: "AGENTS.md#hard-rules",
  message:
    "Visual baselines are approved by a human, never updated by a script or CI.",
};
const SNAPSHOT_UPDATE = /--update-snapshots\b|playwright test\b.*\s-u(?:\s|$)/;
const AUTOMATION_FILES = [
  /^\.github\/workflows\/[^/]+\.ya?ml$/,
  /^framework\/setup\/starter\/\.github\/workflows\/[^/]+\.ya?ml$/,
  /^package\.json$/,
  /^install\.sh$/,
];

function repositoryFiles(): string[] {
  return execSync("git ls-files --cached --others --exclude-standard", {
    cwd: ROOT,
  })
    .toString()
    .split("\n")
    .filter((file) => file && fs.existsSync(path.join(ROOT, file)));
}

// Heading anchors as Markdown renders them, mapped to their titles.
function headings(markdownFile: string): Map<string, string> {
  const file = path.join(ROOT, markdownFile);
  if (!fs.existsSync(file)) return new Map();

  return new Map(
    [...fs.readFileSync(file, "utf8").matchAll(/^#{1,6} (.+)$/gm)].map(
      ([, title]) => [
        title
          .trim()
          .toLowerCase()
          .replace(/[^\w\s-]/g, "")
          .replace(/\s/g, "-"),
        title.trim(),
      ],
    ),
  );
}

// "(AGENTS.md → Layer Rules)", or undefined when the cited section is missing.
function citation(source: string): string | undefined {
  const [file, anchor] = source.split("#");
  const title = headings(file).get(anchor);

  return title ? `(${file} → ${title})` : undefined;
}

const cite = (source: string) => citation(source) ?? `(${source})`;

function missingCitations(files: string[]): string[] {
  return files
    .filter((file) => RULE_FILES.test(file))
    .flatMap((file) =>
      [...fs.readFileSync(path.join(ROOT, file), "utf8").matchAll(CITATION)]
        .map(([source]) => source)
        .filter((source) => !citation(source))
        .map(
          (source) =>
            `${file} cites ${source}, which does not exist. Every rule must enforce a documented rule.`,
        ),
    );
}

function snapshotUpdates(files: string[]): string[] {
  return files
    .filter((file) => AUTOMATION_FILES.some((pattern) => pattern.test(file)))
    .flatMap((file) =>
      fs
        .readFileSync(path.join(ROOT, file), "utf8")
        .split("\n")
        .flatMap((line, index) =>
          !/^\s*#/.test(line) && SNAPSHOT_UPDATE.test(line)
            ? [
                `${file}:${index + 1} [${SNAPSHOT_UPDATE_CHECK.id}] ${SNAPSHOT_UPDATE_CHECK.message} ${cite(SNAPSHOT_UPDATE_CHECK.source)}`,
              ]
            : [],
        ),
    );
}

// Test plans: every planned API/UI case appears as exactly one test title in
// the spec files the plan lists ("T001_Login_API: accepts ...").

type PlannedCase = { id: string; level: "API" | "UI" };
type PlannedFeature = {
  planPath: string;
  cases: PlannedCase[];
  files: string[];
};

function markdownTableRows(lines: string[]): string[][] {
  return lines
    .filter((line) => /^\s*\|/.test(line))
    .filter((line) => !/^\s*\|\s*:?-{3,}/.test(line))
    .map((line) =>
      line
        .trim()
        .replace(/^\||\|$/g, "")
        .split("|")
        .map((cell) => cell.trim().replace(/^`|`$/g, "")),
    );
}

function planSection(lines: string[], title: string): string[] {
  const start = lines.findIndex((line) => line.trim() === `## ${title}`);
  if (start === -1) return [];
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((line) => /^##\s/.test(line.trim()));
  return rest.slice(0, end === -1 ? undefined : end);
}

function plannedFeatures(files: string[]): PlannedFeature[] {
  return files
    .filter((file) => /^test-plans\/.+\.md$/.test(file))
    .flatMap((planPath) => {
      const lines = fs
        .readFileSync(path.join(ROOT, planPath), "utf8")
        .split("\n");
      const caseRows = markdownTableRows(planSection(lines, "Cases"));
      const fileRows = markdownTableRows(planSection(lines, "Files"));
      if (caseRows.length < 2 || fileRows.length < 2) return [];

      const caseHeader = caseRows[0].map((cell) => cell.toLowerCase());
      const idIndex = caseHeader.indexOf("id");
      const levelIndex = caseHeader.indexOf("level");
      const fileIndex = fileRows[0]
        .map((cell) => cell.toLowerCase())
        .indexOf("path");
      if (idIndex === -1 || levelIndex === -1 || fileIndex === -1) return [];

      const cases = caseRows.slice(1).flatMap((row) => {
        const [id, level] = [row[idIndex], row[levelIndex]];
        return id && (level === "API" || level === "UI")
          ? [{ id, level: level as "API" | "UI" }]
          : [];
      });
      const specs = fileRows
        .slice(1)
        .map((row) => row[fileIndex])
        .filter((file) => /^tests\/(api|ui)\/.*\.spec\.ts$/.test(file));

      return cases.length && specs.length
        ? [{ planPath, cases, files: specs }]
        : [];
    });
}

type SpecTitles = {
  suite?: string;
  titles: { line: number; title: string }[];
  caseIds: string[];
};

// Every node below `root`, depth first.
function descendants(root: TSESTree.Node): TSESTree.Node[] {
  const nodes: TSESTree.Node[] = [];
  const visit = (value: unknown) => {
    if (Array.isArray(value)) value.forEach(visit);
    else if (value && typeof (value as TSESTree.Node).type === "string") {
      nodes.push(value as TSESTree.Node);
      for (const [key, child] of Object.entries(value)) {
        if (key !== "parent") visit(child);
      }
    }
  };
  visit(root);
  return nodes;
}

// The literal text of a title: a string, or a template literal as written
// ("${scenario.caseId}: ${scenario.name}").
function titleText(source: string, node: TSESTree.Node | undefined) {
  if (node?.type === T.Literal && typeof node.value === "string") {
    return node.value;
  }
  return node?.type === T.TemplateLiteral
    ? source.slice(node.range[0] + 1, node.range[1] - 1)
    : undefined;
}

// The suite title, the test titles and the scenario caseId values of a spec,
// read from its syntax tree.
function specTitles(source: string): SpecTitles {
  const nodes = descendants(
    tseslint.parser.parseForESLint(source).ast as TSESTree.Node,
  );
  const calls = nodes.filter(
    (node): node is TSESTree.CallExpression => node.type === T.CallExpression,
  );
  const describe = calls.find(
    ({ callee }) =>
      callee.type === T.MemberExpression &&
      callee.object.type === T.Identifier &&
      callee.object.name === "test" &&
      callee.property.type === T.Identifier &&
      callee.property.name === "describe",
  );

  return {
    suite: describe && titleText(source, describe.arguments[0]),
    titles: calls.flatMap((call) => {
      const title =
        call.callee.type === T.Identifier && call.callee.name === "test"
          ? titleText(source, call.arguments[0])
          : undefined;
      return title === undefined ? [] : [{ line: call.loc.start.line, title }];
    }),
    caseIds: nodes.flatMap((node) =>
      node.type === T.Property &&
      node.key.type === T.Identifier &&
      node.key.name === "caseId" &&
      node.value.type === T.Literal &&
      typeof node.value.value === "string" &&
      /^T[0-9]{3,}_[A-Z][A-Za-z0-9]*_(?:API|E2E)$/.test(node.value.value)
        ? [node.value.value]
        : [],
    ),
  };
}

const CASE_TITLE = /^(T[0-9]{3,}_[A-Z][A-Za-z0-9]*_(API|E2E)):\s+(.+)$/;
const DYNAMIC_TITLE = /^\$\{[^}]*\.caseId\}:\s+\$\{[^}]*\.name\}$/;

function plannedCaseProblems(files: string[]): string[] {
  const problems: string[] = [];
  const rule = (detail: string) =>
    `[${CASE_ID_TITLE_CHECK.id}] ${detail}. ${cite(CASE_ID_TITLE_CHECK.source)}`;
  const features = plannedFeatures(files);
  const occurrences = new Map<string, string[]>();
  // Starter and self-test files are checked as if they were already in their
  // target place.
  const specs = files.flatMap((file) => {
    const logical = file.replace(/^framework\/setup\/(starter|selftest)\//, "");
    return /^tests\/(api|ui)\/.*\.spec\.ts$/.test(logical)
      ? [{ file, logical }]
      : [];
  });

  for (const { file, logical } of specs) {
    const relevant = features.filter((feature) =>
      feature.files.includes(logical),
    );
    if (relevant.length === 0) continue;

    const level = logical.startsWith("tests/api/") ? "API" : "UI";
    const { suite, titles, caseIds } = specTitles(
      fs.readFileSync(path.join(ROOT, file), "utf8"),
    );
    const expected = new Set(
      relevant.flatMap((feature) =>
        feature.cases
          .filter((item) => item.level === level)
          .map((item) => item.id),
      ),
    );
    const seen = new Set<string>();

    if (!suite?.trim() || suite.includes("__")) {
      problems.push(`${file} must use a descriptive test.describe suite title`);
    }
    if (new Set(caseIds).size !== caseIds.length) {
      problems.push(
        `${file} ${rule("table-driven scenario caseId values must be unique")}`,
      );
    }

    let dynamic = false;
    for (const { line, title } of titles) {
      const match = CASE_TITLE.exec(title);
      if (!match) {
        if (DYNAMIC_TITLE.test(title)) dynamic = true;
        else
          problems.push(
            `${file}:${line} ${rule("test title must start with its planned case ID and ': '")}`,
          );
        continue;
      }
      const [, id, suffix] = match;
      if (!expected.has(id)) {
        problems.push(
          `${file}:${line} ${rule(`unknown or wrong-plan case ID ${id}`)}`,
        );
      }
      if (suffix !== (level === "API" ? "API" : "E2E")) {
        problems.push(
          `${file}:${line} ${rule(`${id} suffix does not match ${level}`)}`,
        );
      }
      if (seen.has(id)) {
        problems.push(
          `${file}:${line} ${rule(`duplicate test title ID ${id}`)}`,
        );
      }
      seen.add(id);
    }

    if (dynamic) {
      for (const id of caseIds) {
        if (!expected.has(id)) {
          problems.push(
            `${file} ${rule(`table case ID ${id} is not in the plan for this level`)}`,
          );
        }
        seen.add(id);
      }
    }

    for (const feature of relevant) {
      for (const id of seen) {
        if (!feature.cases.some((item) => item.id === id)) continue;
        const key = `${feature.planPath}#${id}`;
        occurrences.set(key, [...(occurrences.get(key) ?? []), file]);
      }
    }
  }

  for (const feature of features) {
    for (const { id, level } of feature.cases) {
      const found = occurrences.get(`${feature.planPath}#${id}`) ?? [];
      if (found.length === 0) {
        problems.push(
          `${feature.planPath} ${rule(`planned ${level} case ${id} has no matching Playwright title in its listed spec files`)}`,
        );
      } else if (found.length > 1) {
        problems.push(
          `${feature.planPath} ${rule(`planned case ${id} appears in multiple specs: ${found.join(", ")}`)}`,
        );
      }
    }
  }
  return problems;
}

function main(): void {
  const files = repositoryFiles();
  const problems = [
    ...[CASE_ID_TITLE_CHECK, SNAPSHOT_UPDATE_CHECK]
      .filter((check) => !citation(check.source))
      .map(
        (check) =>
          `framework/tools/architecture.ts [${check.id}] cites ${check.source}, which does not exist. Every check must enforce a documented rule.`,
      ),
    ...missingCitations(files),
    ...snapshotUpdates(files),
    ...plannedCaseProblems(files),
  ];

  if (problems.length > 0) {
    console.error(problems.map((problem) => `✖ ${problem}`).join("\n"));
    console.error(`\n${problems.length} architecture rule violation(s).`);
    process.exit(1);
  }

  console.log("✔ test plans, automation files and rule sources are consistent");
}

main();
